export const getAllStates = () => Object.keys(LOCATION_HIERARCHY);

export const getDistricts = (state) => {
  if (!state || !LOCATION_HIERARCHY[state]) return [];
  return Object.keys(LOCATION_HIERARCHY[state]);
};

export const getMandals = (state, district) => {
  if (!state || !district || !LOCATION_HIERARCHY[state]?.[district]) return [];
  return Object.keys(LOCATION_HIERARCHY[state][district]);
};

export const getPanchayats = (state, district, mandal) => {
  if (!state || !district) return [];
  const distObj = LOCATION_HIERARCHY[state]?.[district];
  if (!distObj) return [];

  if (mandal && distObj[mandal]) {
    return Object.keys(distObj[mandal]);
  }

  const panchayats = [];
  Object.values(distObj).forEach((m) => {
    panchayats.push(...Object.keys(m));
  });
  return [...new Set(panchayats)];
};

export const getVillages = (state, district, mandal, panchayat) => {
  if (!state || !district || !LOCATION_HIERARCHY[state]?.[district]) return [];
  const distObj = LOCATION_HIERARCHY[state][district];

  if (mandal && panchayat && distObj[mandal]?.[panchayat]) {
    return distObj[mandal][panchayat];
  }

  // If mandal is not specified, search across all mandals in the district for the panchayat
  if (panchayat) {
    for (const mKey of Object.keys(distObj)) {
      if (distObj[mKey][panchayat]) {
        return distObj[mKey][panchayat];
      }
    }
  }

  // If mandal is specified but no panchayat, return all villages under that mandal
  if (mandal && distObj[mandal]) {
    const allMandalVillages = [];
    Object.values(distObj[mandal]).forEach((vList) => {
      if (Array.isArray(vList)) allMandalVillages.push(...vList);
    });
    return [...new Set(allMandalVillages)];
  }

  return [];
};
